// Builds js/growth-reference.js from the official RCPCH UK-WHO data tables
// (github.com/rcpch/rcpchgrowth-python). Run: node tools/build-growth-reference.mjs
//
// UK-WHO charts for term babies use:
//  - UK90 term reference at birth
//  - WHO 2006 standard from 2 weeks of age
// The printed RCPCH chart deliberately shows no centile lines between birth and
// 2 weeks (the normal early weight dip), so we do the same.

import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";

const here = path.dirname(fileURLToPath(import.meta.url));
const OUT = path.join(here, "..", "js", "growth-reference.js");
const BASE = "https://raw.githubusercontent.com/rcpch/rcpchgrowth-python/live/rcpchgrowth/data_tables";

const uk90 = await (await fetch(`${BASE}/uk90_term.json`)).json();
const who = await (await fetch(`${BASE}/who/who_infants.json`)).json();

const birth = uk90.measurement.weight.female[0];
const whoGirls = who.measurement.weight.female;

// WHO infant table is daily (decimal_age = days / 365.25). Keep ages 14-63 days.
const daily = whoGirls
  .map((r) => ({ ageDays: Math.round(r.decimal_age * 365.25), L: r.L, M: r.M, S: r.S }))
  .filter((r) => r.ageDays >= 14 && r.ageDays <= 63);

const js = `// GENERATED by tools/build-growth-reference.mjs - do not edit by hand.
// Source: RCPCH rcpchgrowth data tables (UK-WHO), girls' weight-for-age.
//   Birth: UK90 term reference (${uk90.acknowledgement_text})
//   2 weeks onwards: WHO 2006 growth standard (daily LMS values)
export const BIRTH_LMS = ${JSON.stringify({ L: birth.L, M: birth.M, S: birth.S })};
export const WHO_GIRLS_WEIGHT_DAILY = ${JSON.stringify(daily)};
`;
writeFileSync(OUT, js);
console.log(`Wrote ${daily.length} daily rows -> ${OUT}`);
